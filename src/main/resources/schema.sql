CREATE TABLE IF NOT EXISTS account (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 username VARCHAR(40) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 role VARCHAR(16) NOT NULL CHECK(role IN ('CUSTOMER','MANAGER','SELLER')),
 full_name VARCHAR(100) NOT NULL
);
CREATE TABLE IF NOT EXISTS customer (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 account_id BIGINT NOT NULL UNIQUE REFERENCES account(id),
 phone VARCHAR(10) NOT NULL UNIQUE,
 email VARCHAR(120) NOT NULL UNIQUE,
 registered_at DATE NOT NULL
);
CREATE TABLE IF NOT EXISTS employee (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 account_id BIGINT NOT NULL UNIQUE REFERENCES account(id),
 employee_code VARCHAR(20) NOT NULL UNIQUE,
 position VARCHAR(30) NOT NULL
);
CREATE TABLE IF NOT EXISTS movie (id BIGINT PRIMARY KEY, title VARCHAR(150) NOT NULL, duration_minutes INT NOT NULL CHECK(duration_minutes>0));
CREATE TABLE IF NOT EXISTS room (id BIGINT PRIMARY KEY, name VARCHAR(50) NOT NULL UNIQUE);
CREATE TABLE IF NOT EXISTS seat (id BIGINT PRIMARY KEY, room_id BIGINT NOT NULL REFERENCES room(id), label VARCHAR(8) NOT NULL, UNIQUE(room_id,label));
CREATE TABLE IF NOT EXISTS showtime (id BIGINT PRIMARY KEY, movie_id BIGINT NOT NULL REFERENCES movie(id), room_id BIGINT NOT NULL REFERENCES room(id), starts_at TIMESTAMP NOT NULL);
CREATE TABLE IF NOT EXISTS invoice (id BIGINT PRIMARY KEY, customer_id BIGINT REFERENCES customer(id), issued_at TIMESTAMP NOT NULL, status VARCHAR(12) NOT NULL CHECK(status IN ('PAID','CANCELLED')));
CREATE TABLE IF NOT EXISTS ticket (id BIGINT PRIMARY KEY, invoice_id BIGINT NOT NULL REFERENCES invoice(id), showtime_id BIGINT NOT NULL REFERENCES showtime(id), seat_id BIGINT NOT NULL REFERENCES seat(id), unit_price DECIMAL(14,0) NOT NULL CHECK(unit_price>=0), UNIQUE(showtime_id,seat_id));
CREATE INDEX IF NOT EXISTS idx_showtime_date ON showtime(starts_at);
CREATE INDEX IF NOT EXISTS idx_ticket_showtime ON ticket(showtime_id);
CREATE INDEX IF NOT EXISTS idx_ticket_invoice ON ticket(invoice_id);
